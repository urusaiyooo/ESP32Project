"""Remove glyphs shadowed by CN -> JA -> TW fallback without changing rendering.

Source font copyright: (c) 2000-2003 /efont/ The Electronic Font Open Laboratory.
Glyph data and metrics are copied verbatim from pinned LovyanGFX 1.2.7 efonts.
"""
from __future__ import annotations
import argparse,ast,json,re,struct
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]

def read_font(path,name):
    source=Path(path).read_text(encoding='utf-8')
    match=re.search(r'const uint8_t '+re.escape(name)+r'\[(\d+)\]\s*=\s*((?:"(?:\\.|[^"\\])*"\s*)+);',source)
    if not match:raise ValueError('Font not found: '+name)
    data=b''.join(ast.literal_eval('b'+s) for s in re.findall(r'"(?:\\.|[^"\\])*"',match[2]))
    declared=int(match[1])
    if len(data)==declared-1:data+=b'\0'
    if len(data)!=declared:raise ValueError('Font length mismatch: '+name)
    return data

def glyphs(data):
    result={};at=23
    while data[at+1]:
        length=data[at+1]
        if length<2:raise ValueError('ASCII glyph length')
        result[data[at]]=data[at:at+length];at+=length
    base=23+int.from_bytes(data[21:23],'big');lut=base;target=base;blocks=[]
    while True:
        delta,upper=struct.unpack_from('>HH',data,lut);target+=delta;blocks.append(target);lut+=4
        if upper==65535:break
    for start in blocks:
        at=start
        while at+2<len(data):
            cp=int.from_bytes(data[at:at+2],'big')
            if not cp:break
            length=data[at+2]
            if length<3 or at+length>len(data):raise ValueError('Unicode glyph length')
            result[cp]=data[at:at+length];at+=length
    return result

def subset(data,keep):
    records=glyphs(data);header=bytearray(data[:23]);ascii_data=bytearray();positions={}
    for cp in sorted(c for c in keep if c<256):
        positions[cp]=len(ascii_data);ascii_data.extend(records[cp])
    for cp,offset in ((65,17),(97,19)):
        position=next((positions[c] for c in sorted(positions) if c>=cp),len(ascii_data))
        header[offset:offset+2]=position.to_bytes(2,'big')
    ascii_data.extend(b'\0\0')
    header[21:23]=len(ascii_data).to_bytes(2,'big')
    cps=sorted(c for c in keep if c>=256)
    blocks=[cps[i:i+64] for i in range(0,len(cps),64)] or [[]]
    payloads=[b''.join(records[c] for c in block)+b'\0\0' for block in blocks]
    lut=bytearray()
    for i,block in enumerate(blocks):
        delta=len(blocks)*4 if i==0 else len(payloads[i-1])
        upper=65535 if i==len(blocks)-1 else block[-1]
        lut.extend(struct.pack('>HH',delta,upper))
    header[0]=len(keep)&255
    return bytes(header+ascii_data+lut+b''.join(payloads))

def lookup(data,cp):
    """Independent lookup matching LovyanGFX U8g2font::getGlyph()."""
    at=23
    if cp<256:
        if cp>=97:at+=int.from_bytes(data[19:21],'big')
        elif cp>=65:at+=int.from_bytes(data[17:19],'big')
        while data[at+1]:
            n=data[at+1]
            if data[at]==cp:return data[at:at+n]
            at+=n
    else:
        at+=int.from_bytes(data[21:23],'big');lut=at
        while True:
            delta,upper=struct.unpack_from('>HH',data,lut);at+=delta;lut+=4
            if upper>=cp:break
        while (code:=int.from_bytes(data[at:at+2],'big')):
            n=data[at+2]
            if code==cp:return data[at:at+n]
            at+=n
    return None

def generate(font_dir,output):
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    notices='// Generated by tools/generate_compact_fonts.py; do not edit.\n// Glyph copyright (c) 2000-2003 /efont/ The Electronic Font Open Laboratory.\n// Original glyph bytes and metrics from LovyanGFX 1.2.7 are preserved.\n'
    header=notices+'#pragma once\n#include <LovyanGFX.hpp>\nnamespace compact_fonts {\n'
    source=notices+'#include "compact_fonts.h"\nnamespace compact_fonts {\n'
    report=[]
    for size in (16,24):
        covered=set()
        for family in ('cn','ja','tw'):
            name=f'lgfx_efont_{family}_{size}'
            data=read_font(Path(font_dir)/f'lgfx_efont_{family}.c',name)
            original=glyphs(data);keep=set(original)-covered;covered.update(original)
            if family=='cn':continue
            reduced=subset(data,keep)
            assert data[1:17]==reduced[1:17],name+' font metrics changed'
            # Check all BMP lookup results, not only characters in current songs.
            for cp in range(65536):
                expected=original.get(cp) if cp in keep else None
                if lookup(reduced,cp)!=expected:raise ValueError(f'{name}: lookup differs at U+{cp:04X}')
            symbol=f'{family}{size}'
            header+=f'extern const lgfx::U8g2font {symbol};\n'
            source+=f'static const uint8_t {symbol}_data[] PROGMEM={{\n'
            source+=''.join(','.join(map(str,reduced[i:i+32]))+',\n' for i in range(0,len(reduced),32))
            source+=f'}};\nconst lgfx::U8g2font {symbol}({symbol}_data);\n'
            report.append({'font':name,'before_bytes':len(data),'after_bytes':len(reduced),'retained_glyphs':len(keep),'removed_shadowed_glyphs':len(original)-len(keep),'bmp_lookups_verified':65536,'glyph_bytes_and_metrics_unchanged':True})
    (output/'compact_fonts.h').write_text(header+'}\n',encoding='utf-8')
    (output/'compact_fonts.cpp').write_text(source+'}\n',encoding='utf-8')
    return report

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font-dir',type=Path,default=ROOT/'firmware/.pio/libdeps/esp32s3_n16r8/LovyanGFX/src/lgfx/Fonts/efont')
    parser.add_argument('--output',type=Path,default=ROOT/'firmware/src')
    parser.add_argument('--report',type=Path)
    args=parser.parse_args();report=generate(args.font_dir,args.output)
    if args.report:args.report.write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps({'fonts':report,'saved_bytes':sum(r['before_bytes']-r['after_bytes'] for r in report)},indent=2))
